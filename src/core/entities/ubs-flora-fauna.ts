/**
 * Anchor candidate: one lemma occurrence, resolved as far as it can be.
 *
 * ── Why this is not yet a backbone-token anchor ────────────────────────────
 * Our annotation anchors are `{verse, position}` over `backbone-token:v1`,
 * whose own meta declares `position_unit: "1-based-source-slot-within-verse"`,
 * `position_basis: non-empty original-language rows sorted by Heb/Greek Sort`,
 * `cross_corpus_position_equivalence: "none"` and
 * `not_equivalent_to: ["MACULA","OSHB"]`.
 *
 * A MARBLE ordinal is *morpheme*-level in MARBLE's segmentation. So it is
 * finer than a backbone-token slot AND counted on a different basis. Turning
 * one into the other needs two steps we have not built: coarsen morpheme →
 * word, then remap that word across corpora. `morphemeOrdinal` is therefore
 * carried through verbatim and NOT written into a `position` field, so that
 * nothing downstream can mistake it for one. Verse-level attachment is exact
 * today; word-level attachment is a further piece of work.
 */
export type UbsFfrAnchor = {
  readonly handbook: UbsFfrHandbook;
  readonly entryKey: string;
  readonly title: string;
  readonly language: string;
  readonly lemma: string;
  readonly bref: string;
  readonly morphemeOrdinal: number | null;
  readonly corpus: UbsFfrCorpus | null;
};

/** Non-throwing text of an element's descendants, with tags flattened. */
export function flattenXmlText(fragment: string): string {
  return fragment
    .replace(/<[^>]*>/g, "")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Split a lemma field into its alternatives. Several are comma-separated pairs
 * — "אֵלָה, אַלָּה", "אֹהֶל, מוֹעֵד" — and a join wants each half.
 */
export function splitLemmaAlternatives(lemma: string): readonly string[] {
  return lemma
    .split(/[,;]/)
    .map((p) => p.trim())
    .filter((p) => p.length > 0);
}

/** Strip Hebrew points and cantillation, and unify final forms, for joining. */
export function hebrewConsonantalSkeleton(input: string): string {
  const FINALS: Readonly<Record<string, string>> = {
    "ך": "כ", // ך → כ
    "ם": "מ", // ם → מ
    "ן": "נ", // ן → נ
    "ף": "פ", // ף → פ
    "ץ": "צ", // ץ → צ
  };
  let out = "";
  for (const ch of input.normalize("NFD")) {
    if (ch >= "א" && ch <= "ת") out += FINALS[ch] ?? ch;
  }
  return out;
}

/** Strip Greek diacritics and case-fold, for joining against MACULA lemmas. */
export function greekLemmaSkeleton(input: string): string {
  // Escapes, not literal combining marks: a literal U+0300-block character in
  // source is invisible and does not survive casual copy/paste editing.
  return input
    .normalize("NFD")
    .replace(/[\u0300-\u036f\u1fbd-\u1fff\u0374\u0375]/g, "")
    .toLowerCase()
    .trim();
}

