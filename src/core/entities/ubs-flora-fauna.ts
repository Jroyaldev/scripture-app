/**
 * A decoded MARBLE reference.
 *
 * `morphemeOrdinal` is the honest name for the trailing field, and the naming
 * is the whole point — see `decodeMarbleReference` for the evidence. It is a
 * 1-based ordinal over *morphemes* (sub-word segments) within the verse, in
 * MARBLE's own segmentation. It is finer than a word index and it is not a
 * character offset.
 */
export type MarbleReference = {
  readonly raw: string;
  readonly corpus: UbsFfrCorpus | null;
  readonly bookNumber: number;
  readonly chapter: number;
  readonly verse: number;
  /** 1-based morpheme ordinal within the verse; null when the raw tail was 0. */
  readonly morphemeOrdinal: number | null;
  /**
   * The raw 5-digit tail as an integer. Kept because `morphemeOrdinal` halves
   * it and 17 of 22,244 tails are odd, so halving is lossy for those.
   */
  readonly rawTail: number;
  /** True when the tail was odd — the halving lost a half-step. */
  readonly tailWasOdd: boolean;
};

const MARBLE_RE = /^([HAGLV]?)(\d{14})$/;

/**
 * Decode one MARBLE reference: `[sigil]BBBCCCVVVTTTTT`.
 *
 * ── Fields, and how each was confirmed ─────────────────────────────────────
 *
 * BBB book, 1-based, contiguous over the 66-book canon then deuterocanon.
 *   Confirmed three independent ways, not assumed:
 *     · Hebrew language sets use exactly books 1–39, all 39 present, none
 *       outside. 1=GEN … 39=MAL. (`00700901500064` → Judges 9:15, the cedar in
 *       Jotham's parable; `01903703500014` → Psalm 37:35.)
 *     · Aramaic language sets use exactly two books, 15 and 27 — EZR and DAN
 *       under this mapping, which are precisely the two books with Aramaic
 *       portions. A one-off numbering would not land on that pair.
 *     · Latin language sets use exactly one book, 82 = 2 Esdras, the
 *       deuterocanonical book extant in Latin rather than Greek.
 *   And 258,116/258,116 SDBH Hebrew references decoded this way hit a verse
 *   that exists in oshb-wlc — zero misses.
 *
 * CCC chapter, VVV verse, both 1-based and zero-padded. No reference in the
 *   corpus has chapter 0 or verse 0, so there is no "whole book/chapter" form.
 *
 * TTTTT the trailing five digits: a *doubled 1-based morpheme ordinal* within
 *   the verse. `morphemeOrdinal = tail / 2`. The evidence, measured over the
 *   257,361 SDBH Hebrew references that carry Strong codes, scored by whether
 *   the OSHB morpheme at the predicted index has one of the entry's Strong
 *   numbers:
 *
 *     hypothesis                          in range        Strong-exact
 *     ---------------------------------   -------------   ------------
 *     morpheme ordinal = tail/2           255,717 99.4%   144,892 56.3%
 *     word position    = tail/2           182,359 70.9%    29,838 11.6%
 *     morpheme ordinal = tail/2 ± 1       257,361  100%   204,999 79.7%
 *
 *   Word-level is refuted: it falls out of range for 29% of references and is
 *   right 11.6% of the time. Morpheme-level is in range for 99.4%. It is not a
 *   character offset either — a character offset would exceed the verse's
 *   morpheme count almost always, where tail/2 stays inside it 99.4% of the
 *   time, and 22,227 of 22,244 tails are even, which a character count would
 *   have no reason to be.
 *
 *   The residual is a *drift*, not noise: exact agreement is 91% at ordinals
 *   1–4 and decays to 23% by ordinal 40+, with the error almost always
 *   positive (+1 18.1%, +2 9.2%, +3 4.6%). MARBLE therefore segments somewhat
 *   finer than OSHB and the excess accumulates through the verse. The specific
 *   extra boundary is NOT identified — the obvious candidate, OSHB's fused
 *   preposition+article segments (`Rd`, `Td`), makes agreement worse when
 *   corrected for (45.5% vs 56.3%), so it is refuted. Treat the ordinal as
 *   exact near the start of a verse and approximate deeper in.
 *
 * Returns null for anything that does not match, rather than throwing: the
 * importer counts malformed references instead of dying on one.
 */
export function decodeMarbleReference(raw: string): MarbleReference | null {
  const trimmed = raw.trim();
  const m = MARBLE_RE.exec(trimmed);
  if (!m) return null;
  const sigil = m[1] ?? "";
  const digits = m[2];
  if (digits === undefined) return null;

  const bookNumber = Number.parseInt(digits.slice(0, 3), 10);
  const chapter = Number.parseInt(digits.slice(3, 6), 10);
  const verse = Number.parseInt(digits.slice(6, 9), 10);
  const rawTail = Number.parseInt(digits.slice(9, 14), 10);

  const corpus =
    sigil === "" ? null : (UBS_FFR_CORPUS_SIGILS[sigil as keyof typeof UBS_FFR_CORPUS_SIGILS] ?? null);

  return {
    raw: trimmed,
    corpus,
    bookNumber,
    chapter,
    verse,
    morphemeOrdinal: rawTail === 0 ? null : Math.floor(rawTail / 2),
    rawTail,
    tailWasOdd: rawTail % 2 === 1,
  };
}

/**
 * MARBLE book number → our `BookCode`, or null when the book is outside the
 * 66-book backbone. `BOOK_CODES` is already in MARBLE's order, which is why
 * this is an index and not a table.
 */
export function marbleBookToBookCode(bookNumber: number): BookCode | null {
  if (!Number.isInteger(bookNumber) || bookNumber < 1 || bookNumber > BOOK_CODES.length) return null;
  return BOOK_CODES[bookNumber - 1] ?? null;
}

/** Name a book we cannot resolve, for diagnostics. */
export function marbleDeuterocanonName(bookNumber: number): string | null {
  return UBS_FFR_DEUTEROCANON_BOOKS[bookNumber] ?? null;
}

/**
 * Why a reference could not be turned into a backbone anchor. Distinguished
 * because they need different responses: `deuterocanon` is a canon-scope fact
 * about us, `versification` is a real divergence to be fixed with a map, and
 * `malformed` would be a source defect.
 */
export type MarbleResolutionFailure =
  | "malformed"
  | "deuterocanon"
  | "unknown-book"
  | "versification";

export type MarbleResolution =
  | { readonly ok: true; readonly book: BookCode; readonly chapter: number; readonly verse: number; readonly morphemeOrdinal: number | null }
  | { readonly ok: false; readonly reason: MarbleResolutionFailure; readonly bookNumber: number; readonly detail: string };

/**
 * Resolve a decoded reference to a verse the backbone admits.
 *
 * `chapterVerseCounts` is the backbone's `books[code].chapters` array. Passing
 * it in keeps this module free of the loader (INV-18).
 *
 * A reference that names an in-canon book but a verse the backbone lacks is
 * reported as `versification`, NOT as bad data. Every one of the 144 such
 * references in the corpus is a textbook Masoretic-versus-English divergence:
 * Joel 4 (English has 3 chapters), Malachi 3:19–24 (English splits a chapter
 * 4), 1 Kings 5:20 (English 4:21–34 = Hebrew 5:1–14), Exodus 21:37 (English
 * 22:1), Numbers 17:23, Psalm superscriptions counted as verse 1. The
 * references are correct for the Masoretic text; our backbone is numbered the
 * other way. Resolving them needs a versification map, which we do not yet
 * have.
 */
export function resolveMarbleReference(
  ref: MarbleReference,
  chapterVerseCounts: (code: BookCode) => readonly number[] | undefined,
): MarbleResolution {
  const code = marbleBookToBookCode(ref.bookNumber);
  if (!code) {
    const dc = marbleDeuterocanonName(ref.bookNumber);
    return dc
      ? { ok: false, reason: "deuterocanon", bookNumber: ref.bookNumber, detail: dc }
      : { ok: false, reason: "unknown-book", bookNumber: ref.bookNumber, detail: `book ${ref.bookNumber}` };
  }
  const chapters = chapterVerseCounts(code);
  if (!chapters) {
    return { ok: false, reason: "unknown-book", bookNumber: ref.bookNumber, detail: code };
  }
  const maxVerse = chapters[ref.chapter - 1];
  if (ref.chapter < 1 || maxVerse === undefined) {
    return {
      ok: false,
      reason: "versification",
      bookNumber: ref.bookNumber,
      detail: `${code} ${ref.chapter} beyond ${chapters.length} chapters`,
    };
  }
  if (ref.verse < 1 || ref.verse > maxVerse) {
    return {
      ok: false,
      reason: "versification",
      bookNumber: ref.bookNumber,
      detail: `${code} ${ref.chapter}:${ref.verse} beyond ${maxVerse} verses`,
    };
  }
  return { ok: true, book: code, chapter: ref.chapter, verse: ref.verse, morphemeOrdinal: ref.morphemeOrdinal };
}

/** Backbone reference string, matching `toBref` in `src/core/reference`. */
export function marbleToBref(r: Extract<MarbleResolution, { ok: true }>): string {
  return `bref:v1/${r.book}.${r.chapter}.${r.verse}`;
}

