/**
 * The corpus sigil that may prefix a reference. It marks *which text* the
 * reference indexes, and it is NOT the same thing as the entry's
 * `LanguageSet Language`: 1,704 references sit in a Greek language set but
 * carry `L`, and 20 sit in a Hebrew set carrying `A`. FLORA and FAUNA omit the
 * sigil entirely (all 5,507 of their references are bare); only REALIA writes
 * it. Absent means "the text implied by the book number".
 *
 * The mapping below is inferred from distribution, and two of the four
 * inferences are load-bearing enough to state the evidence:
 *   L — 1,704 refs, every one in books 67+ (deuterocanon). Septuagint.
 *   V — 108 refs, every one in book 82, and book 82 is the *only* book any
 *       Latin language set points at. 2 Esdras survives in Latin, not Greek,
 *       which is why the Latin sets and the V sigil coincide there. Vulgate.
 */
export const UBS_FFR_CORPUS_SIGILS = {
  H: "masoretic-hebrew",
  A: "biblical-aramaic",
  G: "greek-new-testament",
  L: "septuagint",
  V: "vulgate-latin",
} as const;

export type UbsFfrCorpus = (typeof UBS_FFR_CORPUS_SIGILS)[keyof typeof UBS_FFR_CORPUS_SIGILS];

