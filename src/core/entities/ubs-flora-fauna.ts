/**
 * A per-image copyright string, kept verbatim plus whatever structure could be
 * read off it without guessing.
 *
 * `raw` is the contract. `holder`, `source` and `licenseHint` are conveniences
 * for grouping and MUST NOT be used as the displayed credit — the raw string
 * is what the source asserts and the only thing safe to show.
 */
export type UbsFfrCopyright = {
  readonly raw: string;
  /** Best-effort holder with a leading "©" and a trailing source clause removed. */
  readonly holder: string;
  /** e.g. "Wikimedia Commons", "Pixabay", when the string names one. */
  readonly source: string | null;
  /** A CC/PD token found in the string, verbatim, e.g. "CC BY-SA 3.0", "CC0". */
  readonly licenseHint: string | null;
  /** True when the string names no attributable holder at all. */
  readonly unattributable: boolean;
  /** True when the string says the image is model-generated. */
  readonly machineGenerated: boolean;
};

const SOURCE_PATTERNS: ReadonlyArray<readonly [RegExp, string]> = [
  // "Wikimedia Coomons" / "Wikimedia Common" are upstream typos; match them.
  [/Wikimedia\s+Comm?o?n?s?/i, "Wikimedia Commons"],
  [/Wikiedia\s+Commons/i, "Wikimedia Commons"],
  [/Pixabay/i, "Pixabay"],
  [/Metropolitan\s+Museum\s+of\s+Art/i, "Metropolitan Museum of Art"],
  [/Israel\s+Government\s+Press\s+Office/i, "Israel Government Press Office"],
  [/British\s+Museum/i, "British Museum"],
  [/Library\s+of\s+Congress/i, "Library of Congress"],
  [/archive\.org/i, "archive.org"],
  [/Flickr/i, "Flickr"],
  [/USDA/i, "USDA"],
];

const LICENSE_HINT_RE =
  /\bCC0\b|\bCC\s+BY(?:-SA)?(?:\s+\d(?:\.\d)?)?(?:\s+[A-Z]{2})?\b|\bPublic\s+domain\b/i;

const UNATTRIBUTABLE_RE = /^\(?\s*source\s+unknown\s*\)?$/i;

const MACHINE_RE = /\bChatGPT\b|\bOpenAI\b|\bDALL[-·\s]?E\b|\bMidjourney\b/i;

/**
 * Structure a copyright string without losing it.
 *
 * Deliberately conservative. Ray Pritz alone appears as "Ray Pritz (UBS)",
 * "© Ray Pritz (UBS)", "© Ray Pritz by United Bible Societies" and
 * "© Ray Pritz (UBS" (an unclosed parenthesis upstream). Normalising those to
 * one holder is useful for a count and *wrong* as a credit, so both forms are
 * returned and the caller decides.
 */
export function parseImageCopyright(rawInput: string): UbsFfrCopyright {
  const raw = rawInput.trim();
  if (raw === "") {
    return { raw, holder: "", source: null, licenseHint: null, unattributable: true, machineGenerated: false };
  }
  if (UNATTRIBUTABLE_RE.test(raw)) {
    return { raw, holder: raw, source: null, licenseHint: null, unattributable: true, machineGenerated: false };
  }

  let source: string | null = null;
  for (const [re, name] of SOURCE_PATTERNS) {
    if (re.test(raw)) {
      source = name;
      break;
    }
  }
  const licenseMatch = LICENSE_HINT_RE.exec(raw);
  const licenseHint = licenseMatch ? licenseMatch[0].replace(/\s+/g, " ") : null;

  // Holder: drop a leading ©, then cut at the first clause that is plainly a
  // source or licence rather than a name.
  let holder = raw.replace(/^\s*©\s*/, "");
  const cut = holder.search(
    /\s*(?:\(|,\s*(?:CC0|CC\s+BY|Public\s+domain|via\b)|\s+via\b|\s*-\s*Wikimedia|\s*©\s*Wikimedia|\s+by\s+United\s+Bible\s+Societies)/i,
  );
  if (cut > 0) holder = holder.slice(0, cut);
  holder = holder.replace(/\s+/g, " ").trim();

  return {
    raw,
    holder,
    source,
    licenseHint,
    unattributable: holder === "",
    machineGenerated: MACHINE_RE.test(raw),
  };
}

